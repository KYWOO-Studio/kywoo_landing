#!/usr/bin/env python3
"""Build en.html (English version) from index.html (Chinese, the main version).

  python3 scripts/build-en.py

Every Chinese text node and attribute value in index.html is replaced with its
English entry in scripts/i18n_en.py. If any Chinese string has no entry, the
script lists it and stops without writing, so edit index.html first, add the
English line, then rebuild. Scripts read <html lang> for their own UI strings.
"""
import html
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from i18n_en import EN  # noqa: E402

CJK = re.compile(r'[　-〿一-鿿＀-￯]')
missing = []


def tr(raw, quote):
    key = raw.strip()
    if key not in EN:
        missing.append(key)
        return raw
    lead = raw[:len(raw) - len(raw.lstrip())]
    trail = raw[len(raw.rstrip()):]
    return lead + html.escape(EN[key], quote=quote) + trail


def translate(chunk):
    # attribute values first, then text between tags
    chunk = re.sub(r'(\s[\w:-]+)="([^"]*)"',
                   lambda m: m.group(1) + '="' + (tr(m.group(2), True) if CJK.search(m.group(2)) else m.group(2)) + '"', chunk)
    chunk = re.sub(r'>([^<]+)<', lambda m: '>' + (tr(m.group(1), False) if CJK.search(m.group(1)) else m.group(1)) + '<', chunk)
    return chunk


src = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
parts = re.split(r'(<script\b.*?</script>|<style\b.*?</style>)', src, flags=re.S)
out = ''.join(p if p.startswith('<script') or p.startswith('<style') else translate(p) for p in parts)

if missing:
    print('Missing English for %d string(s):' % len(set(missing)))
    for m in dict.fromkeys(missing):
        print('  ', repr(m))
    sys.exit(1)

swaps = [
    ('<html lang="zh-CN">', '<html lang="en">'),
    ('<a class="lang-switch" href="./en" hreflang="en" lang="en">EN</a>',
     '<a class="lang-switch" href="./" hreflang="zh-CN" lang="zh-CN">中文</a>'),
    ('<a href="./en" hreflang="en" lang="en">English</a>',
     '<a href="./" hreflang="zh-CN" lang="zh-CN">中文</a>'),
]
for a, b in swaps:
    if out.count(a) != 1:
        sys.exit('Expected exactly one: ' + a)
    out = out.replace(a, b)
out = out.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-en.py from index.html. Do not edit by hand. -->', 1)

left = [l.strip() for l in out.split('\n') if CJK.search(l) and '中文' not in l]
left = [l for l in left if not l.startswith('<script')]
if left:
    print('Chinese text still present (check):')
    for l in left[:20]:
        print('  ', l[:160])

open(os.path.join(ROOT, 'en.html'), 'w', encoding='utf-8').write(out)
print('wrote en.html', len(out), 'bytes')
